// World-Map packs: a highlighted country on a public-domain world map (sourced
// from Wikimedia Commons "BlankMap-World.svg"). The player names the country.
//
// We ship the world map ONCE at `/public/maps/world.svg` and highlight the
// requested country at render time — the question carries a `mapIso` field
// (lowercase ISO 3166-1 alpha-2) which the CountryMap component uses to inject
// a `<style>` rule into the shared markup. That keeps the deployment lean
// (~850 KB total) instead of shipping 200 copies of the same map.
//
// hideBoardLetters: true → the board uses chess-style coordinates instead of
// per-hex letters, and the question card prompt is generic ("Name the
// country") so the first letter never leaks.

import type { RawPack, RawQuestion } from '../core/packs';

const PROMPT = 'Name the highlighted country.';

const q = (country: string, iso: string, alt?: string[]): RawQuestion => ({
  q: PROMPT,
  a: country,
  mapIso: iso,
  ...(alt ? { alt } : {}),
});

