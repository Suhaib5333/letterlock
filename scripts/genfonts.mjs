// Bundle the Google Fonts we use into public/fonts/ and emit src/fonts.css.
//
// Why: the app must not depend on fonts.googleapis.com at boot (store review on
// restricted networks, offline play, privacy). All five families are OFL licensed
// (see public/fonts/LICENSES.md), so shipping the files ourselves is allowed.
//
// How: ask the Google Fonts CSS2 API for our exact font request with a modern
// browser UA (so it answers with woff2 + unicode-range subsets), keep only the
// subsets we need (latin, latin-ext, arabic), download each woff2 once (a variable
// font shares one file across weights; identical URLs are deduped) and rewrite the
// @font-face rules to local /fonts/ URLs. Re-runnable: existing files are skipped.
//
// Run:  node scripts/genfonts.mjs
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = join(import.meta.dirname, '..');
const OUT_DIR = join(ROOT, 'public', 'fonts');
const CSS_OUT = join(ROOT, 'src', 'fonts.css');

// Exactly the request index.html used to make (keep in sync if a weight is added).
const FAMILIES = [
  'Atkinson+Hyperlegible:wght@400;700',
  'Bricolage+Grotesque:opsz,wght@12..96,600;12..96,700;12..96,800',
  'Lexend:wght@400;500;600;700',
  'Sora:wght@400;500;600;700',
  'Tajawal:wght@400;500;700;800',
];
const API = `https://fonts.googleapis.com/css2?${FAMILIES.map((f) => `family=${f}`).join('&')}&display=swap`;
const UA =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/128.0.0.0 Safari/537.36';
const KEEP_SUBSETS = new Set(['latin', 'latin-ext', 'arabic']);

const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)/g, '');

const res = await fetch(API, { headers: { 'User-Agent': UA } });
if (!res.ok) throw new Error(`Google Fonts CSS API HTTP ${res.status}`);
const css = await res.text();

// Parse "/* subset */ @font-face { ... }" blocks.
const blocks = [];
const re = /\/\*\s*([a-z-]+)\s*\*\/\s*@font-face\s*\{([^}]*)\}/g;
let m;
while ((m = re.exec(css))) {
  const subset = m[1];
  const body = m[2];
  const get = (prop) => (body.match(new RegExp(`${prop}:\\s*([^;]+);`)) || [])[1]?.trim();
  const family = get('font-family')?.replace(/^['"]|['"]$/g, '');
  const weight = get('font-weight');
  const style = get('font-style') || 'normal';
  const stretch = get('font-stretch');
  const range = get('unicode-range');
  const url = (body.match(/url\(([^)]+)\)/) || [])[1];
  if (!family || !weight || !url) continue;
  blocks.push({ subset, family, weight, style, stretch, range, url });
}
if (blocks.length === 0) throw new Error('No @font-face blocks parsed (did Google change the CSS format?)');

const kept = blocks.filter((b) => KEEP_SUBSETS.has(b.subset));
console.log(`Parsed ${blocks.length} @font-face blocks, keeping ${kept.length} (${[...KEEP_SUBSETS].join(', ')})`);

mkdirSync(OUT_DIR, { recursive: true });
const fileByUrl = new Map();
let downloaded = 0, skipped = 0;
for (const b of kept) {
  if (fileByUrl.has(b.url)) continue;
  const name = `${slug(b.family)}-${b.subset}-${b.weight}.woff2`;
  const path = join(OUT_DIR, name);
  fileByUrl.set(b.url, name);
  if (existsSync(path)) { skipped++; continue; }
  const r = await fetch(b.url, { headers: { 'User-Agent': UA } });
  if (!r.ok) throw new Error(`HTTP ${r.status} for ${b.url}`);
  const buf = Buffer.from(await r.arrayBuffer());
  if (buf.length < 1000 || buf.toString('ascii', 0, 4) !== 'wOF2') throw new Error(`Not a woff2: ${b.url}`);
  writeFileSync(path, buf);
  downloaded++;
  console.log(`  ↓ ${name} (${(buf.length / 1024).toFixed(0)} KB)`);
}

const out = [
  '/* Self-hosted web fonts (generated by scripts/genfonts.mjs, do not edit by hand).',
  ' * Files live in public/fonts/; licenses in public/fonts/LICENSES.md.',
  ' * Subsets kept: latin, latin-ext, arabic. Weights match the old Google Fonts request. */',
  '',
];
for (const b of kept) {
  out.push(`/* ${b.family} ${b.weight} ${b.subset} */`);
  out.push('@font-face {');
  out.push(`  font-family: '${b.family}';`);
  out.push(`  font-style: ${b.style};`);
  out.push(`  font-weight: ${b.weight};`);
  if (b.stretch) out.push(`  font-stretch: ${b.stretch};`);
  out.push('  font-display: swap;');
  out.push(`  src: url(/fonts/${fileByUrl.get(b.url)}) format('woff2');`);
  if (b.range) out.push(`  unicode-range: ${b.range};`);
  out.push('}');
}
writeFileSync(CSS_OUT, out.join('\n') + '\n');
console.log(`\nWROTE ${CSS_OUT} (${kept.length} rules), ${fileByUrl.size} files (${downloaded} downloaded, ${skipped} already present)`);
