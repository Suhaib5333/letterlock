/**
 * Build expanded "Guess the Logo" tiers from Simple Icons, with EVERY slug
 * verified against cdn.simpleicons.org (HTTP 200 + real SVG) so no dead/broken
 * logos ship. Brand title lists come from scripts/logobrands.mjs. Output:
 * src/content/logosExtra.ts (logosEasyExtra / logosMediumExtra / logosHardExtra).
 */
import { writeFileSync } from 'node:fs';
import { easy, medium, hard } from './logobrands.mjs';
import { easyMore, mediumMore } from './logobrands_more.mjs';

// Simple Icons' official title→slug algorithm (matches cdn.simpleicons.org).
function titleToSlug(title) {
  return title
    .toLowerCase()
    .replace(/\+/g, 'plus')
    .replace(/\./g, 'dot')
    .replace(/&/g, 'and')
    .replace(/đ/g, 'd')
    .replace(/ħ/g, 'h')
    .replace(/ı/g, 'i')
    .replace(/ĸ/g, 'k')
    .replace(/ŀ/g, 'l')
    .replace(/ł/g, 'l')
    .replace(/ß/g, 'ss')
    .replace(/ŧ/g, 't')
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .replace(/[^a-z0-9]/g, '');
}

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function verify(slug) {
  for (let attempt = 0; attempt < 3; attempt++) {
    try {
      const res = await fetch(`https://cdn.simpleicons.org/${slug}`);
      if (res.ok) {
        const t = await res.text();
        if (t.includes('<svg')) return true;
      }
      return false;
    } catch {
      await sleep(600 + attempt * 600);
    }
  }
  return false;
}

// Resolve a brand to a verified {brand, slug} or null. Tries the canonical slug
// plus a couple of common fallbacks.
async function resolve(brand) {
  const base = titleToSlug(brand);
  const candidates = [base, base.replace(/inc$|corp$|company$/, ''), brand.toLowerCase().replace(/[^a-z0-9]/g, '')];
  for (const slug of [...new Set(candidates)].filter(Boolean)) {
    if (await verify(slug)) return { brand, slug };
    await sleep(120);
  }
  return null;
}

async function resolveTier(brands) {
  const out = [];
  const seen = new Set();
  for (const brand of brands) {
    if (seen.has(brand.toLowerCase())) continue;
    seen.add(brand.toLowerCase());
    const r = await resolve(brand);
    if (r) out.push(r);
    else console.log('  drop (no icon):', brand);
  }
  return out;
}

function emit(name, entries) {
  const byLetter = {};
  for (const { brand, slug } of entries) {
    const L = brand.trim()[0].toUpperCase();
    if (L < 'A' || L > 'Z') continue;
    (byLetter[L] ??= []).push({ brand, slug });
  }
  const lines = [`export const ${name}: Record<string, RawQuestion[]> = {`];
  for (const L of Object.keys(byLetter).sort()) {
    lines.push(`  ${L}: [`);
    for (const { brand, slug } of byLetter[L]) lines.push(`    q(${JSON.stringify(brand)}, ${JSON.stringify(slug)}),`);
    lines.push('  ],');
  }
  lines.push('};');
  return lines.join('\n');
}

console.log('Resolving EASY...');
const e = await resolveTier([...easy, ...easyMore]);
console.log('Resolving MEDIUM...');
const m = await resolveTier([...medium, ...mediumMore]);
console.log('Resolving HARD...');
const h = await resolveTier(hard);

const header = `import type { RawQuestion } from '../core/packs';

// Auto-generated by scripts/genlogos.mjs — every slug verified against
// cdn.simpleicons.org. Answer = brand name; the board hides letters.
const logo = (slug: string): string => \`https://cdn.simpleicons.org/\${slug}\`;
const PROMPT = 'Which brand does this logo belong to?';
function q(brand: string, slug: string, alt?: string[]): RawQuestion {
  return { q: PROMPT, a: brand, image: logo(slug), category: 'logos', ...(alt ? { alt } : {}) };
}
`;

writeFileSync('src/content/logosExtra.ts', `${header}\n${emit('logosEasyExtra', e)}\n\n${emit('logosMediumExtra', m)}\n\n${emit('logosHardExtra', h)}\n`);
console.log(`\nWROTE src/content/logosExtra.ts — easy ${e.length}, medium ${m.length}, hard ${h.length}`);
