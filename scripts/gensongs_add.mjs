const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
async function lookupOnce(title, artist) {
  const term = encodeURIComponent(`${title} ${artist}`);
  const url = `https://itunes.apple.com/search?term=${term}&entity=song&limit=5&country=US`;
  const ac = new AbortController();
  const timer = setTimeout(() => ac.abort(), 8000);
  let res;
  try {
    res = await fetch(url, { signal: ac.signal });
  } finally {
    clearTimeout(timer);
  }
  const text = await res.text();
  if (!text.trim().startsWith('{')) throw new Error('non-JSON');
  const data = JSON.parse(text);
  const a = artist.toLowerCase().replace(/[^a-z]/g, '');
  const pick =
    (data.results || []).find((r) => r.previewUrl && (r.artistName || '').toLowerCase().replace(/[^a-z]/g, '').includes(a.slice(0, 6))) ||
    (data.results || []).find((r) => r.previewUrl);
  return pick?.previewUrl || null;
}
async function lookup(t, a) {
  for (let i = 0; i < 2; i++) {
    try {
      const p = await lookupOnce(t, a);
      if (p) return p;
    } catch {}
    await sleep(900 + i * 700);
  }
  return null;
}

const byLetter = {};
let ok = 0;
for (const [title, artist, answer, alts] of NEW_SONGS) {
  let preview = null;
  try {
    preview = await lookup(title, artist);
  } catch {}
  await sleep(600);
  if (!preview) {
    console.log('skip:', answer);
    continue;
  }
  const L = answer.trim()[0].toUpperCase();
  if (L < 'A' || L > 'Z') continue;
  (byLetter[L] ??= []).push({ a: answer, audio: preview, alts: alts || [artist] });
  ok++;
  console.log('ok:', answer);
}

const lines = [`import type { RawPack } from '../core/packs';`, '', '// More iTunes-preview songs merged into the songs pack. Generated by scripts/gensongs_add.mjs.', 'export const songsExtra: RawPack[\'letters\'] = {'];
for (const L of Object.keys(byLetter).sort()) {
  lines.push(`  '${L}': [`);
  for (const q of byLetter[L]) {
    lines.push(`    { q: 'Name this famous song.', a: ${JSON.stringify(q.a)}, audio: ${JSON.stringify(q.audio)}, category: 'music', alt: ${JSON.stringify(q.alts.map((x) => x.toLowerCase()))} },`);
  }
  lines.push('  ],');
}
lines.push('};');
writeFileSync('src/content/songsExtra.ts', lines.join('\n') + '\n');
console.log(`\nWROTE src/content/songsExtra.ts — ${ok} songs`);
